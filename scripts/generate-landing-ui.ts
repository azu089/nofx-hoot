async function main() {
  try {
    console.log('正在调用 v0 API 生成 Landing Page UI...')

    const chat = await v0.chats.create({
      message: prompt,
      system: '你是一个专业的 React/Next.js 前端开发专家，擅长使用 Tailwind CSS 和 shadcn/ui 创建现代化的深色主题金融类 Web 应用。生成的代码要完整、可运行。',
    })

    console.log('\n✅ 生成成功！')
    console.log(`🔗 查看生成的 UI: ${chat.webUrl}`)
    console.log(`📝 Chat ID: ${chat.id}`)

  } catch (error) {
    console.error('生成失败:', error)
  }
}

main()
